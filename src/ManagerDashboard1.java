    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        SessionFactory sf = new Configuration().configure().buildSessionFactory();
        Session session = sf.openSession();
        Transaction tx = session.beginTransaction();

        String manid = jTextField11.getText();

        Manager man = (Manager)session.get(Manager.class,manid);
        if(man==null){
            JOptionPane.showMessageDialog(this,"No such Record Found!!");
        }
        else{
            String fullname = jTextField12.getText();
            long contact = Long.parseLong(jTextField13.getText());
            String email = jTextField14.getText();
            String gender="";
            if(jRadioButton3.isSelected())
            gender="Female";
            if(jRadioButton4.isSelected())
            gender="Male";
            DateModel dm = jDatePicker2.getModel();
            String DOB = dm.getDay()+" "+dm.getMonth()+" "+dm.getYear();
            String address = jTextField16.getText();
            String qualification = jTextField17.getText();

            man.setFullname(fullname);
            man.setContact(contact);
            man.setEmail(email);
            man.setGender(gender);
            man.setDob(DOB);
            man.setAddress(address);
            man.setQualification(qualification);

            session.update(man);
            tx.commit();
            session.close();
            JOptionPane.showMessageDialog(this,"Account Updated!!");
        }

    }//GEN-LAST:event_jButton4ActionPerformed

