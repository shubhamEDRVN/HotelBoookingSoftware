    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String id = jTextField2.getText();

        char ch1[] = jPasswordField2.getPassword();
        String opwd = new String(ch1);

        char ch2[] = jPasswordField3.getPassword();
        String npwd = new String(ch2);

        char ch3[] = jPasswordField4.getPassword();
        String cnpwd = new String(ch3);

        SessionFactory sf = new Configuration().configure().buildSessionFactory();
        org.hibernate.Session session = sf.openSession();
        Transaction tx = session.beginTransaction();

        Criteria crit = session.createCriteria(Manager.class);
        crit.add(Restrictions.and(Restrictions.eq("manid",id),Restrictions.eq("password",opwd)));
        List<Manager>list=crit.list();
        if(list.isEmpty())
        {

            JOptionPane.showMessageDialog(this,"Invalid Id/Old Password!!");
        }
        else
        {
            if(npwd.equals(cnpwd)){
                Manager man = (Manager)session.get(Manager.class, id);
                man.setPassword(npwd);
                session.update(man);
                tx.commit();
                session.close();
                new WindowAfterFlash().setVisible(true);
                dispose();
            }
            else{
                JOptionPane.showMessageDialog(this,"New Password and Confirm New Password does not match.");
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

