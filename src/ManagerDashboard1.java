    void loadRecords()
    {
        SessionFactory sf = new Configuration().configure().buildSessionFactory();
        Session session = sf.openSession();
        Transaction tx = session.beginTransaction();
        
        Criteria crit = session.createCriteria(Room.class);
        List<Room>list=crit.list();
        dtm = (DefaultTableModel)jTable1.getModel();
        for(Room entry:list){
            Object records[]={entry.getRoomno(),entry.getStatus(), entry.getCapacity(), entry.getAmount(), entry.getFeatures()};
            dtm.addRow(records);
        }
    }
    void loadBooking()
    {
        SessionFactory sf = new Configuration().configure().buildSessionFactory();
        Session session = sf.openSession();
        Transaction tx = session.beginTransaction();
        
        Criteria crit = session.createCriteria(Booking.class);
        List<Booking>list=crit.list();
        dtm = (DefaultTableModel)jTable2.getModel();
        for(Booking entry:list){
            Object records[]={entry.getBookingid(),entry.getRoomno(),entry.getFullname(),entry.getContact(),entry.getEmail(),entry.getAge(),entry.getGender()};
            dtm.addRow(records);
        }
    }
    
    void loadRoom(int roomno){
        SessionFactory sf = new Configuration().configure().buildSessionFactory();
        Session session = sf.openSession();
        Transaction tx = session.beginTransaction();
        
        Criteria crit = session.createCriteria(Room.class);
        Room entry = (Room)session.get(Room.class,roomno);
        
        dtm = (DefaultTableModel)jTable3.getModel();
        Object records[]={entry.getRoomno(),entry.getStatus(), entry.getCapacity(), entry.getAmount(), entry.getFeatures()};
        dtm.addRow(records);
    }

